"""Dump every actor (NPC, trainer, item ball, boulder...) of the extension maps (>= 540) to a markdown table, read from the ROM: object id, sprite, flag, script id, tile, facing, and for trainers the trainer id and name.
Script ids: 1..N = the map's own bank, 3000+ = shared trainer scripts (trainer id = script - 2999), 10000+ = common scripts. A local script that holds opcode 213 (TrainerBattle) gives the trainer id.
Output is generated: re-run after a build instead of editing by hand. Usage: id_dump.py <rom.nds> <out.md>"""
import struct
import sys
import ndspy.narc
import ndspy.rom
import map_header_extension as ext
from opening import events_decode
from parcel_quest import split_bank


def main(rom_path, out):
    rom = ndspy.rom.NintendoDSRom.fromFile(rom_path)
    events = ndspy.narc.NARC(rom.getFileByName('a/0/3/2')).files
    scripts = ndspy.narc.NARC(rom.getFileByName('a/0/1/2')).files
    lines = [f'# Actor / trainer ids of the extension maps (generated by tools/id_dump.py from {rom_path.split("/")[-1]})', '',
             'obj = actor object id on that map; script 1..N local, 3000+ shared trainer (id = script - 2999); trainer = id (defeat flag 0x550 + id). Tile = global x,z.', '']
    for i, rec in enumerate(ext.records(rom)):
        m = ext.NATIVE_COUNT + i
        g = events_decode(bytes(events[struct.unpack_from('<H', rec, 16)[0]]))
        try:
            bank = split_bank(bytes(scripts[struct.unpack_from('<H', rec, 6)[0]]))
        except Exception:
            bank = []
        lines += [f'## map {m}  ({len(g[1])} actors, {len(g[0])} bg/signs, {len(g[2])} warps, {len(g[3])} triggers)', '', '| obj | sprite | flag | script | tile | face | trainer |', '|---|---|---|---|---|---|---|']
        for a in g[1]:
            obj, sprite, _, _, flag, script, face = struct.unpack_from('<7H', a, 0)
            x, z = struct.unpack_from('<2H', a, 24)
            tid = None
            if 3000 <= script < 10000:
                tid = script - 2999
            elif 1 <= script <= len(bank):
                j = bytes(bank[script - 1]).find(b'\xd5\x00')
                if j >= 0:
                    tid = struct.unpack_from('<H', bank[script - 1], j + 2)[0]
            who = '' if tid is None else str(tid)          # the trainer name table (text 729) holds only blank placeholders for these ids
            lines.append(f'| {obj} | {sprite} | {flag:#x} | {script} | {x},{z} | {face} | {who} |')
        lines.append('')
    open(out, 'w').write('\n'.join(lines))
    print(len(lines), 'lines')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
